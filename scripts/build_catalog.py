#!/usr/bin/env python3
"""Build the local search catalogue and the script-free edition (stdlib only)."""
from pathlib import Path
from html import escape
from html.parser import HTMLParser
from urllib.parse import urlsplit
import json,re

ROOT=Path(__file__).resolve().parents[1]
PREFIX='/bygagarin-portfolio/'
BASE='https://oprimeroman-art.github.io'+PREFIX
EXCLUDE={'about/index.html','prototype/index.html','404.html','plain/index.html','qa.html'}
SKIP={'cover-scene','directory-preview','cover-bottom','inner-subnav','inner-meta','inner-index','casefile-aside','bio-sticky','index-filters','featured-select','section-topline','brief','liquid-stage','liquid-modes','case-liquid-demo','laboratory-live','motion-lab','cover-foot'}
VOID={'area','base','br','col','embed','hr','img','input','link','meta','param','source','track','wbr'}
ALLOWED={'p','ul','ol','li','h1','h2','h3','h4','strong','b','em','i','a','dl','dt','dd','blockquote','br'}

def slug(path):return path.replace('/index.html','').replace('index.html','home').replace('/','--')
paths=sorted(p for p in ROOT.rglob('*.html') if not any(part.startswith('.') or part in ('dist','versions') for part in p.relative_to(ROOT).parts) and 'en' not in p.relative_to(ROOT).parts and 'en' not in p.relative_to(ROOT).parts and str(p.relative_to(ROOT)) not in EXCLUDE)
urls={PREFIX+str(p.relative_to(ROOT)).replace('index.html',''):slug(str(p.relative_to(ROOT))) for p in paths}

class Content(HTMLParser):
 def __init__(self,path):
  super().__init__(convert_charrefs=True);self.path=path;self.stack=[];self.inside=False;self.skip=False;self.text=[];self.output=[];self.heading=False;self.title=[];self.title_open=False;self.page_slug=slug(path)
 def handle_starttag(self,tag,attrs):
  a=dict(attrs)
  if tag=='main':self.inside=True
  if tag=='h1':self.title_open=True
  active=self.inside and not self.skip
  skip=self.skip or tag in {'script','style','nav','noscript','form','button','canvas','svg'} or bool(SKIP.intersection(a.get('class','').split())) or 'hidden' in a
  emit=active and not skip and tag in ALLOWED
  name={'h1':'h2','h2':'h3','h3':'h4','h4':'h5'}.get(tag,tag)
  if emit:
   attrs_out=''
   if tag=='a' and a.get('href'):
    href=a['href'];u=urlsplit(href)
    if href.startswith('#'):href='#'+self.page_slug+'--'+href[1:]
    elif href.startswith(PREFIX) or href.startswith(BASE):
     path=u.path
     if path in urls:href='#'+urls[path]+('--'+u.fragment if u.fragment else '')
    attrs_out+=' href="'+escape(href,quote=True)+'"'
   if a.get('id'):attrs_out+=' id="'+self.page_slug+'--'+escape(a['id'],quote=True)+'"'
   self.output.append('<'+name+attrs_out+'>')
  if self.inside and not skip and a.get('id') and not emit:self.output.append('<a id="'+self.page_slug+'--'+escape(a['id'],quote=True)+'"></a>')
  if tag not in VOID:self.stack.append((tag,self.skip,emit,name));self.skip=skip
 def handle_endtag(self,tag):
  if tag=='h1':self.title_open=False
  if not self.stack:return
  if self.stack[-1][0]!=tag:return
  _,previous,emit,name=self.stack.pop()
  if emit:self.output.append('</'+name+'>\n')
  self.skip=previous
  if tag=='main':self.inside=False
 def handle_data(self,data):
  if self.title_open:self.title.append(data)
  if self.inside and not self.skip:
   self.text.append(data);self.output.append(escape(data))

entries=[];sections=[]
for path in paths:
 rel=str(path.relative_to(ROOT));parser=Content(rel);parser.feed(path.read_text());title=' '.join(' '.join(parser.title).split())
 title={'index.html':'Главная — byGagarin','services/index.html':'Решения','projects/index.html':'Работы','experience/index.html':'Биография','tools/index.html':'Инструменты','publications/index.html':'Публикации и интервью','books/index.html':'Книги','archive/index.html':'Архив'}.get(rel,title)
 section='Проект' if rel.startswith('projects/') else 'Книга' if rel.startswith('books/') else 'Раздел'
 priority=12 if rel=='index.html' else 8 if rel.count('/')==1 else 1
 entries.append({'title':title,'url':PREFIX+rel.replace('index.html',''),'section':section,'priority':priority,'text':' '.join(' '.join(parser.text).split())})
 sections.append('<section id="'+slug(rel)+'">'+''.join(parser.output)+'<p><a href="#contents">К оглавлению</a> · <a href="'+PREFIX+rel.replace('index.html','')+'">Открыть с оформлением</a></p></section>')
(ROOT/'assets/search-index.js').write_text('/* Generated by scripts/build_catalog.py. All destinations are real HTML documents. */\nwindow.GAGARIN_SEARCH = '+json.dumps(entries,ensure_ascii=False,separators=(',',':'))+';\n')
plain=ROOT/'plain';plain.mkdir(exist_ok=True)
links=''.join('<li><a href="#'+slug(str(p.relative_to(ROOT)))+'">'+escape(e['title'])+'</a></li>' for p,e in zip(paths,entries))
(plain/'index.html').write_text('<!doctype html>\n<html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex,follow"><meta name="description" content="Текстовая версия сайта Романа Гагарина: работы, биография, книги и публикации."><title>byGagarin — простая версия</title><link rel="icon" href="'+PREFIX+'assets/images/roman-pixel.png" type="image/png">\n<link rel="icon" href="'+PREFIX+'favicon.svg?v=pixel-20261118" type="image/svg+xml">\n<link rel="apple-touch-icon" href="'+PREFIX+'assets/images/roman-pixel.png"><link rel="canonical" href="'+BASE+'"><style>body{max-width:850px;margin:20px auto;padding:0 16px;font:17px/1.7 Arial,sans-serif;color:#172320;background:#f2f3f0}a{color:#17654b}h1,h2,h3,h4,h5{line-height:1.2}section{border-top:1px solid #a7baae;padding:25px 0}li{margin:6px 0}p{overflow-wrap:break-word}a{word-wrap:break-word}dt{font-weight:bold}dd{margin:0 0 12px}</style></head><body><header><h1>byGagarin — Роман Гагарин</h1><p>Работы, биография, книги и публикации. Эта версия открывается без JavaScript, графических эффектов и загрузки шрифтов.</p><p><a href="'+PREFIX+'">Открыть основной сайт</a></p><nav id="contents" aria-label="Оглавление"><ul>'+links+'</ul></nav></header><main>'+''.join(sections)+'</main></body></html>')
print('Built search for',len(entries),'documents and the plain edition.')
